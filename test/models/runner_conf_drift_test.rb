require "test_helper"

# The drift pin for the config-in-a-model files whose whole job is to MIRROR a
# service: FluxConf mirrors chopshop-flux (config.py + models.py + the route
# list in docs/API.md), PlotConf mirrors the chopshop-bp repo's chopshop_plot
# package (config.py, spec.py, server.py, metrics.py and the route table in
# docs/contract.md), and Telemetry's #telemetry-config tables mirror the
# chopshop-svg pipeline (scripts/triage_ranker.py + scripts/triage.py). Every
# one of them says the same thing in its own header -- anything in them that
# drifts from the service is a bug in the conf -- and until this test existed
# nothing checked it.
#
# WHY A FIXTURE AND NOT A LIVE READ: the studio's test suite runs inside a
# container that mounts THIS repo only. The siblings are on the host, so a test
# that read chopshop_flux/models.py at test time would pass on one machine and
# error on the next. test/fixtures/runner_conf_drift.json is the checked-in
# transcription, generated by reading those repos, and it is the pin.
#
# The live read is ALSO here, as a second check that the fixture itself has not
# gone stale: point CHOPSHOP_SIBLING_ROOT at the directory holding the siblings
# (the default guess is this repo's parent) and the fixture is re-derived from
# the services' own files and compared with what it claims. It is deliberately
# not a dependency -- absent siblings, the fixture-only assertions still run,
# because the fixture is the pin and the live read is the convenience.
class RunnerConfDriftTest < ActiveSupport::TestCase
  FIXTURE = Rails.root.join("test", "fixtures", "runner_conf_drift.json").freeze

  # The three size rules models.py carries PER MODEL, which is the drift that
  # made the FLUX page accept requests the service 400s.
  DIM_FIELDS = %w[dim_multiple min_dim max_pixels].freeze

  def fixture
    @fixture ||= JSON.parse(FIXTURE.read)
  end

  def flux_fixture
    fixture["chopshop_flux"]
  end

  def plot_fixture
    fixture["chopshop_plot"]
  end

  # chopshop-svg, the ML/ranking pipeline Telemetry's #telemetry-config mirrors.
  def svg_fixture
    fixture["chopshop_svg"]
  end

  # "POST /generate, POST /digest, GET /health" -> ["POST /generate", ...]
  def routes_of(list)
    list.scan(%r{(?:GET|POST) \S+}).map { |route| route.chomp(",") }
  end

  # -- the fixture itself ---------------------------------------------------

  test "the fixture is checked in, generated, and says where its numbers came from" do
    assert FIXTURE.file?, "#{FIXTURE} must be checked in: it is the pin"
    generated = fixture["_generated"].to_s
    assert_includes generated, "chopshop-flux", "the fixture must name the service it was read from"
    assert_includes generated, "chopshop-bp"
    assert_includes generated, "chopshop-svg"
    assert_includes generated, "models.py"
    assert_includes generated, "config.py"
    assert_includes generated, "triage_ranker.py"
    assert_includes generated, "triage.py"
    # The rule the fixture exists for: the container cannot read the siblings,
    # so the file -- not a live read -- is what the assertions compare against.
    assert_match(/container does NOT mount the siblings/i, generated)
    assert_match(/regenerate/i, generated, "and must say what to do when a service changes")
  end

  # -- FluxConf, against chopshop-flux --------------------------------------

  test "FluxConf carries the service's own config.py constants" do
    config = flux_fixture["config"]
    assert_equal config["DEFAULT_BIND"], FluxConf::DEFAULT_BIND
    assert_equal config["DEFAULT_PORT"], FluxConf::DEFAULT_PORT
    assert_equal config["DIMENSION_MULTIPLE"], FluxConf::DIMENSION_MULTIPLE,
      "the klein family's alignment, in config.py"
    assert_equal config["MIN_DIMENSION"], FluxConf::MIN_DIMENSION
    assert_equal config["DEFAULT_MAX_PIXELS"], FluxConf::DEFAULT_MAX_PIXELS
    assert_equal config["MAX_UPLOAD_BYTES"], FluxConf::MAX_UPLOAD_BYTES
  end

  test "FluxConf registers exactly the models the service's registry does" do
    assert_equal flux_fixture["models"].keys.sort, FluxConf::MODELS.keys.sort,
      "a model the service registers and the page does not offer (or the reverse) is drift"
    assert_equal flux_fixture["default_model"], FluxConf::DEFAULT_MODEL_KEY
  end

  test "every model carries the service's OWN dim constraints, not one family's" do
    flux_fixture["models"].each do |key, expected|
      spec = FluxConf::MODELS.fetch(key)
      DIM_FIELDS.each do |field|
        assert_equal expected.fetch(field), spec.fetch(field),
          "#{key}: #{field} is #{expected[field]} on the ModelSpec; the conf must carry " \
          "that, because one family's rules applied to another is the bug"
      end
      # And the page reads them through the one reader #facts and #validate use,
      # so neither can hold a second copy.
      assert_equal expected.slice(*DIM_FIELDS), FluxConf.limits(key),
        "#{key}: FluxConf.limits must be the model's own three rules"
    end
  end

  test "FluxConf carries the service's schedule, licence and calling convention per model" do
    flux_fixture["models"].each do |key, expected|
      spec = FluxConf::MODELS.fetch(key)
      %w[repo_id licence].each do |field|
        assert_equal expected[field], spec[field], "#{key}: #{field}"
      end
      %w[commercial_ok gated distilled negative_prompt img2img_strength].each do |field|
        assert_equal expected[field], spec[field], "#{key}: #{field}"
      end
      assert_equal expected["default_steps"], spec["default_steps"], "#{key}: steps"
      assert_equal expected["default_guidance"], spec["default_guidance"], "#{key}: guidance"
    end
  end

  test "FluxConf transcribes the registry's aliases and notes verbatim" do
    # "The values are transcribed, not paraphrased" is the file's own rule, and
    # the aliases are what a caller may pass as `model`: an alias the service
    # resolves and this list does not name is a model the page cannot describe.
    flux_fixture["models"].each do |key, expected|
      spec = FluxConf::MODELS.fetch(key)
      assert_equal expected["aliases"].sort, spec["aliases"].sort, "#{key}: aliases"
      assert_equal expected["notes"].squeeze(" "), spec["notes"].squeeze(" "), "#{key}: notes"
    end
  end

  test "FluxConf lists every route the service answers, and no others" do
    assert_equal flux_fixture["routes"].sort, routes_of(FluxConf::API[:routes]).sort,
      "the service serves six routes (docs/API.md) and the conf must list all six"
  end

  test "FluxConf.validate enforces the SELECTED model's rules, exactly as models.py does" do
    # The concrete symptom of the old drift, in both directions: SDXL and SD 1.5
    # are multiples of 8 from 128, so 128x128 is legal on them and ILLEGAL on
    # klein; and sdxl-turbo's 1 MP cap refuses a size klein accepts.
    sd = FluxConf.validate(width: "136", height: "136", images: "1",
                           model_key: "sdxl-1.0", guidance: "5.0", ack: "0")
    assert_empty sd[:problems],
      "136 is a multiple of 8 from 128: legal on SDXL"

    klein = FluxConf.validate(width: "136", height: "136", images: "1",
                              model_key: "klein-4b", guidance: "1.0", ack: "0")
    assert_includes klein[:problems].join(" "), "width must be a multiple of 16, got 136",
      "the same size is illegal on klein, which is the whole reason the rules are per model"

    turbo = FluxConf.validate(width: "2048", height: "2048", images: "1",
                              model_key: "sdxl-turbo", guidance: "0.0", ack: "1")
    assert_includes turbo[:problems].join(" "), "over the 1048576 cap",
      "sdxl-turbo's own cap is 1 MP, not klein's 4"
    assert_empty FluxConf.validate(width: "2048", height: "2048", images: "1",
                                   model_key: "klein-4b", guidance: "1.0",
                                   ack: "0")[:problems],
      "and 4 MP is exactly klein's cap, so it is allowed there"
  end

  test "the facts the page hands the browser carry each model's own rules" do
    facts = FluxConf.facts
    assert_equal FluxConf::MODELS.keys, facts["models"].keys
    flux_fixture["models"].each do |key, expected|
      spec = facts["models"].fetch(key)
      assert_equal expected["min_dim"], spec["min_dim"], "#{key}: min_dim reaches the browser"
      assert_equal expected["dim_multiple"], spec["dim_multiple"]
      assert_equal expected["max_pixels"], spec["max_pixels"]
    end
  end

  # -- PlotConf, against the chopshop-bp repo's chopshop_plot package -------

  test "PlotConf carries the service's own config.py constants and schema version" do
    assert_equal plot_fixture["config"]["DEFAULT_BIND"], PlotConf::DEFAULT_BIND
    assert_equal plot_fixture["config"]["DEFAULT_PORT"], PlotConf::DEFAULT_PORT
    assert_equal plot_fixture["config"]["MAX_BODY_BYTES"], PlotConf::MAX_BODY_BYTES
    assert_equal plot_fixture["metrics_version"], PlotConf::METRICS_VERSION
  end

  test "PlotConf carries all six operations, and validates every one of them" do
    assert_equal plot_fixture["operations"], PlotConf::OPERATIONS.map { |op| op["name"] },
      "server.py's OPERATIONS tuple is the service's own list: six, not three"
    PlotConf::OPERATIONS.each do |op|
      assert_equal op["name"], op["op"], "#{op['name']}: the route, the op and the name are one"
      assert op["takes"].present?, "#{op['name']} must say what it takes"
      assert op["draws"].present?, "#{op['name']} must say what it draws"
      # An operation this page lists but would refuse is worse than not listing
      # it: the Checks card offers every one of these in its op select.
      result = PlotConf.validate(op: op["name"], chart: "scatter",
                                 x: "node_count_max", y: "mae_art", color: nil)
      refute_includes result[:problems].join(" "), "must be one of",
        "#{op['name']} is in OPERATIONS, so validate must not reject it as unknown"
      assert_empty result[:problems], "#{op['name']} must be a legal op"
    end
  end

  test "PlotConf lists every route the service answers, and no others" do
    assert_equal plot_fixture["routes"].sort, routes_of(PlotConf::API[:routes]).sort,
      "six operations, /files/<name> and /health — the eight docs/contract.md tabulates"
  end

  test "PlotConf carries the contract's element vocabulary and required fields" do
    required = plot_fixture["element_required_fields"]
    assert_equal required.keys.sort, PlotConf::ELEMENTS.keys.sort
    required.each do |type, fields|
      assert_equal fields, PlotConf::ELEMENTS[type],
        "#{type}: the required fields are spec.py's, and a missing one is not a default"
    end
  end

  test "PlotConf carries the contract's chart lists and the digest default size" do
    assert_equal plot_fixture["digest_charts"], PlotConf::DIGEST_CHARTS
    assert_equal plot_fixture["default_size"], PlotConf::DEFAULT_SIZE,
      "digest.py's own fallback, not a guess"
  end

  # -- Telemetry, against the chopshop-svg pipeline --------------------------

  # Telemetry's #telemetry-config tables are prose with the shipped values
  # embedded in <mono> spans. Until this test existed nothing checked the
  # transcription; the file's own header said a re-worded number here "would
  # make the STATUS page a page that lies about the pipeline it describes", and
  # nothing enforced it.
  MONO = /<mono>(.*?)<\/mono>/m

  def mono_spans(entries)
    entries.flat_map { |entry| entry[:body].scan(MONO).flatten }
  end

  # The values back OUT of the prose. Both "<mono>learn_min_picks=30</mono>"
  # and "<mono>max_speckles 40 · min_luma_delta 12</mono>" are read here, into
  # {"learn_min_picks" => "30", "max_speckles" => "40", ...}. Only <mono> spans
  # are read, so a number in the surrounding sentence ("a handful", "top-8") is
  # never mistaken for a shipped value. The assertions downstream compare the
  # NUMBERS: a sentence re-worded around the same number still passes, a
  # re-worded number is the bug being caught.
  def mono_values(entries)
    text = mono_spans(entries).join(" · ")
    values = {}
    text.scan(/([a-z_][a-z0-9_]*)\s*=\s*([0-9]+(?:\.[0-9]+)?)/) { |key, value| values[key] = value }
    text.scan(/([a-z_][a-z0-9_]*)\s+([0-9]+(?:\.[0-9]+)?)(?![\w.])/) { |key, value| values[key] ||= value }
    values
  end

  # Telemetry shows the pipeline's values under the names an operator writes in
  # spec.json; the fixture keeps the pipeline's own constant names. This
  # translation is the test's, not the prose's -- it is what "the same value"
  # means, and triage_ranker.py is where each name resolves (COLD_START_PICKS
  # and LEARN_MIN_JOBS via load_triage's learn_min_picks/learn_min_jobs).
  RANKER_PROSE_TO_CONST = {
    "learn_min_picks" => "COLD_START_PICKS",
    "learn_min_jobs"  => "LEARN_MIN_JOBS",
    "n_random_slots"  => "DEFAULT_RANDOM_SLOTS",
    "window"          => "RANK_VISIBLE_WINDOW"
  }.freeze

  test "Telemetry's cold-start and anti-feedback numbers are triage_ranker.py's constants" do
    values = mono_values(Telemetry::RANKER)
    RANKER_PROSE_TO_CONST.each do |prose, const|
      expected = svg_fixture["ranker"].fetch(const)
      actual = values[prose]
      refute_nil actual,
        "Telemetry no longer states #{prose}: the shipped value must stay on the page"
      assert_equal expected.to_f, actual.to_f,
        "Telemetry says #{prose}=#{actual} but triage_ranker.py ships #{const}=#{expected}"
    end
  end

  test "Telemetry's bandit epsilon and TTL are triage_ranker.py's constants" do
    epsilon = svg_fixture["ranker"].fetch("DEFAULT_EPSILON_EXPLORE")
    actual = mono_values(Telemetry::BANDIT)["epsilon"]
    refute_nil actual, "Telemetry no longer states the explore rate"
    assert_equal epsilon.to_f, actual.to_f,
      "Telemetry says epsilon #{actual} but triage_ranker.py ships " \
      "DEFAULT_EPSILON_EXPLORE=#{epsilon}"

    # The TTL is stated in days in the prose, and ships as seconds in
    # BANDIT_TTL_SECONDS = 30 * 24 * 3600 -- a named constant, so it IS
    # pinnable; the translation to days is the test's.
    ttl = svg_fixture["ranker"].fetch("BANDIT_TTL_SECONDS")
    days = Telemetry::BANDIT.map { |entry| entry[:body] }.join(" ")[/expire after (\d+) days/, 1]
    refute_nil days, "Telemetry must say how long the bucket statistics live"
    assert_equal (ttl / 86_400).to_f, days.to_f,
      "Telemetry says the TTL is #{days} days but triage_ranker.py ships " \
      "BANDIT_TTL_SECONDS=#{ttl} (#{ttl / 86_400} days)"
  end

  test "Telemetry's triage-gate defaults are triage.py's TRIAGE_DEFAULTS" do
    values = mono_values(Telemetry::GATES)
    svg_fixture["triage_defaults"].each do |key, expected|
      actual = values[key]
      refute_nil actual,
        "Telemetry no longer states the #{key} gate default: the shipped value must stay on the page"
      assert_equal expected.to_f, actual.to_f,
        "Telemetry says #{key} #{actual} but triage.py's TRIAGE_DEFAULTS ships #{key} #{expected}"
    end
  end

  test "Telemetry names the pipeline's own learned-ranker file" do
    assert_includes mono_spans(Telemetry::LEARNING),
      svg_fixture["ranker"].fetch("RANKER_FILENAME"),
      "triage_ranker.py reads RANKER_FILENAME; the LEARNING table must name that file"
  end

  # -- the fixture's own currency, checked live when the siblings are readable

  def sibling(rel)
    roots = [ENV["CHOPSHOP_SIBLING_ROOT"], File.expand_path("..", Rails.root)].compact
    roots.map { |root| Pathname.new(root).join(rel) }.find(&:file?)
  end

  # A Python int expression: "8", "1024 * 1024", "2 * 1024 * 1024".
  def int_expr(raw)
    return nil unless raw
    factors = raw.split("*").map(&:strip)
    return nil unless factors.all? { |f| f.match?(/\A\d+\z/) }
    factors.map(&:to_i).inject(:*)
  end

  def flux_live_models
    path = sibling("chopshop-flux/chopshop_flux/models.py")
    return nil unless path
    config = sibling("chopshop-flux/chopshop_flux/config.py")&.read.to_s
    defaults = {
      "dim_multiple" => int_expr(config[/^DIMENSION_MULTIPLE\s*=\s*(.+)$/, 1]),
      "min_dim" => int_expr(config[/^MIN_DIMENSION\s*=\s*(.+)$/, 1]),
      "max_pixels" => int_expr(config[/^DEFAULT_MAX_PIXELS\s*=\s*(.+)$/, 1])
    }
    block = path.read.split("REGISTRY: dict[str, ModelSpec] = {", 2).last
    block.split(/\n    "/).drop(1).select { |part| part.include?("ModelSpec(") }.to_h do |part|
      key = part[/\A([^"]+)/, 1]
      body = part.split("ModelSpec(", 2).last
      entry = DIM_FIELDS.to_h do |field|
        value = int_expr(body[/\b#{field}=([^,\n]+)/, 1]&.strip)
        [field, value || defaults[field]]
      end
      entry["default_steps"] = int_expr(body[/\bdefault_steps=([^,\n]+)/, 1]&.strip)
      entry["default_guidance"] = body[/\bdefault_guidance=([^,\n]+)/, 1]&.strip&.to_f
      [key, entry]
    end
  end

  test "the flux half of the fixture is still what models.py says" do
    live = flux_live_models
    if live.nil?
      assert_nil live,
        "the siblings are not readable from here (#{Rails.root}) — the fixture above is the " \
        "pin; set CHOPSHOP_SIBLING_ROOT to the directory holding chopshop-flux to re-check it"
      return
    end
    live.each do |key, entry|
      expected = flux_fixture["models"].fetch(key)
      DIM_FIELDS.each do |field|
        assert_equal entry[field], expected[field],
          "#{key}/#{field}: the fixture says #{expected[field]}, models.py now says " \
          "#{entry[field]} — regenerate the fixture and fix whichever conf drifted"
      end
      assert_equal entry["default_steps"], expected["default_steps"], "#{key}: steps"
      assert_equal entry["default_guidance"], expected["default_guidance"], "#{key}: guidance"
    end
  end

  test "the plot half of the fixture is still what server.py and contract.md say" do
    server = sibling("chopshop-bp/chopshop_plot/server.py")&.read
    contract = sibling("chopshop-bp/docs/contract.md")&.read
    if server.nil? || contract.nil?
      assert_nil server && contract,
        "the siblings are not readable from here (#{Rails.root}) — the fixture above is the " \
        "pin; set CHOPSHOP_SIBLING_ROOT to the directory holding chopshop-bp to re-check it"
      return
    end
    live_ops = server[/OPERATIONS = \(([^)]*)\)/, 1].to_s.scan(/"([^"]+)"/).flatten
    assert_equal live_ops, plot_fixture["operations"],
      "server.py's OPERATIONS tuple has moved: regenerate the fixture and check PlotConf::OPERATIONS"
    live_routes = contract.scan(/^\| `((?:GET|POST) [^`]+)` \|/).flatten
    assert_equal live_routes.sort, plot_fixture["routes"].sort,
      "docs/contract.md's route table has moved: regenerate the fixture and check PlotConf::API"
  end

  test "the svg half of the fixture is still what triage_ranker.py and triage.py say" do
    ranker = sibling("chopshop-svg/scripts/triage_ranker.py")&.read
    triage = sibling("chopshop-svg/scripts/triage.py")&.read
    if ranker.nil? || triage.nil?
      assert_nil ranker && triage,
        "the siblings are not readable from here (#{Rails.root}) — the fixture above is the " \
        "pin; set CHOPSHOP_SIBLING_ROOT to the directory holding chopshop-svg to re-check it"
      return
    end

    live = {
      "COLD_START_PICKS" => int_expr(ranker[/^COLD_START_PICKS\s*=\s*(.+)$/, 1]),
      "LEARN_MIN_JOBS" => int_expr(ranker[/^LEARN_MIN_JOBS\s*=\s*(.+)$/, 1]),
      "DEFAULT_RANDOM_SLOTS" => int_expr(ranker[/^DEFAULT_RANDOM_SLOTS\s*=\s*(.+)$/, 1]),
      "RANK_VISIBLE_WINDOW" => int_expr(ranker[/^RANK_VISIBLE_WINDOW\s*=\s*(.+)$/, 1]),
      "BANDIT_TTL_SECONDS" => int_expr(ranker[/^BANDIT_TTL_SECONDS\s*=\s*(.+)$/, 1]),
      "DEFAULT_EPSILON_EXPLORE" => ranker[/^DEFAULT_EPSILON_EXPLORE\s*=\s*(.+)$/, 1]&.strip&.to_f,
      "RANKER_FILENAME" => ranker[/^RANKER_FILENAME\s*=\s*"([^"]+)"/, 1]
    }
    live.each do |const, value|
      expected = svg_fixture["ranker"].fetch(const)
      assert_equal expected, value,
        "#{const}: the fixture says #{expected}, triage_ranker.py now says #{value} — " \
        "regenerate the fixture and fix Telemetry's prose"
    end

    # TRIAGE_DEFAULTS is a dict literal; read the keys the fixture pins, so a
    # key triage.py adds and Telemetry does not show is not this test's business.
    defaults = triage.split("TRIAGE_DEFAULTS = {", 2).last.to_s.split("}", 2).first
    svg_fixture["triage_defaults"].each do |key, expected|
      raw = defaults[/"#{key}":\s*([0-9]+(?:\.[0-9]+)?)/, 1]
      value = raw && (raw.include?(".") ? raw.to_f : raw.to_i)
      assert_equal expected, value,
        "TRIAGE_DEFAULTS/#{key}: the fixture says #{expected}, triage.py now says #{value} — " \
        "regenerate the fixture and fix Telemetry's prose"
    end
  end
end
